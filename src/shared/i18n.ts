export type MessageParams = Record<string, string | number>

let activeLocale: Locale = DEFAULT_LOCALE

export function isLocale(value: unknown): value is Locale {
  return value === 'es' || value === 'en' || value === 'pt'
}

export function setLocale(locale: Locale): void {
  activeLocale = locale
}

export function getLocale(): Locale {
  return activeLocale
}

function interpolate(text: string, params?: MessageParams): string {
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (match, key: string) =>
    params[key] === undefined ? match : String(params[key])
  )
}

export function t(source: string, params?: MessageParams): string {
  const table = activeLocale === 'en' ? EN : activeLocale === 'pt' ? PT : null
  return interpolate(table?.[source] ?? source, params)
}

